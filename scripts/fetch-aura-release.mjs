/**
 * Fetches GitHub latest release assets and writes src/generated/aura-sanctuary-downloads.ts
 * Run via: npm run update:aura-release
 * Runs automatically before production build (prebuild).
 *
 * Optional env: GITHUB_TOKEN — raises API rate limit (useful in CI).
 */
import { writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT = join(ROOT, 'src', 'generated', 'aura-sanctuary-downloads.ts');

const REPO = 'EtritHasolli/aura-sanctuary';
const API = `https://api.github.com/repos/${REPO}/releases/latest`;

/** Used only when the API fails and no output file exists yet. */
const FALLBACK_VERSION = '1.0.19';

function fallbackDownloads(version) {
  const base = `https://github.com/${REPO}/releases/download/v${version}`;
  return [
    { label: 'Windows', href: `${base}/Aura-Sanctuary-Setup-${version}.exe` },
    { label: 'macOS (Intel)', href: `${base}/Aura-Sanctuary-${version}.dmg` },
    { label: 'macOS (Apple Silicon)', href: `${base}/Aura-Sanctuary-${version}-arm64.dmg` },
    { label: 'Linux', href: `${base}/Aura-Sanctuary-${version}.AppImage` },
  ];
}

function pickDownloads(assets) {
  if (!Array.isArray(assets) || assets.length === 0) return null;

  let windows;
  let macIntel;
  let macArm;
  let linux;

  for (const a of assets) {
    const name = a.name ?? '';
    const href = a.browser_download_url;
    if (!href || typeof href !== 'string') continue;

    const lower = name.toLowerCase();

    if (name.endsWith('.AppImage')) {
      linux = { label: 'Linux', href };
      continue;
    }
    if (name.endsWith('.dmg')) {
      if (lower.includes('arm64')) {
        macArm = { label: 'macOS (Apple Silicon)', href };
      } else {
        macIntel = { label: 'macOS (Intel)', href };
      }
      continue;
    }
    if (name.endsWith('.exe')) {
      const isSetup = lower.includes('setup');
      if (!windows || isSetup) {
        windows = { label: 'Windows', href };
      }
    }
  }

  const ordered = [windows, macIntel, macArm, linux].filter(Boolean);
  return ordered.length ? ordered : null;
}

function emitSource({ downloads, tagNote }) {
  const json = JSON.stringify(downloads, null, 2);
  return `/* eslint-disable */
/**
 * Auto-generated by scripts/fetch-aura-release.mjs — do not edit by hand.
 * ${tagNote}
 */
export const auraSanctuaryDownloads: { label: string; href: string }[] = ${json};
`;
}

async function main() {
  mkdirSync(dirname(OUT), { recursive: true });

  const headers = {
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }

  try {
    const res = await fetch(API, { headers });
    if (!res.ok) {
      throw new Error(`GitHub API ${res.status} ${res.statusText}`);
    }
    const data = await res.json();
    const tag = data.tag_name ?? 'unknown';
    const picked = pickDownloads(data.assets);
    if (!picked) {
      throw new Error('No matching release assets (.exe, .dmg, .AppImage) found.');
    }
    writeFileSync(OUT, emitSource({ downloads: picked, tagNote: `Source: ${API} (tag ${tag}).` }), 'utf8');
    console.log(`Wrote ${OUT} from release ${tag} (${picked.length} downloads).`);
    return;
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    console.warn(`[fetch-aura-release] ${msg}`);

    if (existsSync(OUT)) {
      console.warn(`Keeping existing ${OUT}.`);
      return;
    }

    const fb = fallbackDownloads(FALLBACK_VERSION);
    writeFileSync(
      OUT,
      emitSource({
        downloads: fb,
        tagNote: `Fallback v${FALLBACK_VERSION} (API error: ${msg}).`,
      }),
      'utf8',
    );
    console.warn(`Created ${OUT} using fallback v${FALLBACK_VERSION}.`);
  }
}

await main();
